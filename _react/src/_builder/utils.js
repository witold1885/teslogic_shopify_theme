const processSeoHtml = (html) => {
  let seoHtml = html
  for (const [placeholder, liquid] of Object.entries(liquidVariables)) {
    seoHtml = seoHtml.replaceAll(placeholder, liquid)
  }
  return seoHtml.replaceAll('\n', '')
}


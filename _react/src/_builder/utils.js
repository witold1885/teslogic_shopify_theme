import fs from 'fs'
import path from 'path'

const __dirname = import.meta.dirname

const assetsDir = path.resolve(__dirname, '../../../assets')
const snippetsDir = path.resolve(__dirname, '../../../snippets')
const sectionsDir = path.resolve(__dirname, '../../../sections')

const media = { desktop: '(min-width: 577px)', mobile: '(max-width: 576px)' }

export const getFiles = () => fs.readdirSync(assetsDir)

export const processDirs = () => {
  if (fs.existsSync(assetsDir)) {
    console.log('Cleaning old assets...')
    getFiles().forEach((file) => {
      const isOldChunk = file.startsWith('react-chunk-')
      const isOldStyle = file.startsWith('react-style-')
      const isOldAsset = file.startsWith('react-') && /-[a-zA-Z0-9]{8,}\.[a-zA-Z0-9]+$/.test(file)
      if (isOldChunk || isOldStyle || isOldAsset) {
        try {
          fs.unlinkSync(path.join(assetsDir, file))
        } catch (err) {
          console.error(`Can not delete old asset ${file}:`, err)
        }
      }
    })
  }

  if (!fs.existsSync(snippetsDir)) {
    fs.mkdirSync(snippetsDir, { recursive: true })
  }
}

export const saveSnippet = (name, content) => {
  const snippetPath = path.resolve(snippetsDir, `${name}.liquid`)
  fs.writeFileSync(snippetPath, content, 'utf-8')
  console.log(`Saved snippet: snippets/${name}.liquid`)
}

export const saveSection = (name, content) => {
  const sectionPath = path.resolve(sectionsDir, `${name}.liquid`)
  fs.writeFileSync(sectionPath, content, 'utf-8')
  console.log(`Saved section: sections/${name}.liquid`)
}

export const generateFontsSnippet = () => {
  const fontSourceDir = path.resolve(__dirname, '../assets/fonts/Manrope')
  const fontsMap = { Regular: 400, Medium: 500, SemiBold: 600, Bold: 700 }

  Object.keys(fontsMap).forEach(key => {
    const file = `Manrope-${key}.woff2`
    fs.copyFileSync(
      path.join(fontSourceDir, file),
      path.join(assetsDir, `react-${file}`)
    )
  })
    
  const fonts = getFiles().filter(f => f.startsWith('react-Manrope-') && f.endsWith('.woff2')).map(file => ({
    url: file,
    weight: fontsMap[file.match(/(?<=react-[A-Za-z]+-)[A-Za-z]+/)[0]] || null
  }))

  let preloadFontTags = '', fontStyles = ''

  fonts.forEach(({ url, weight }) => {
    preloadFontTags += `<link rel="preload" href="{{ '${url}' | asset_url }}" as="font" type="font/woff2" crossorigin>\n`
    fontStyles += `
@font-face {
    font-family: 'Manrope';
    src: url({{ '${url}' | asset_url }}) format('woff2');
    font-weight: ${weight};
    font-style: normal;
    font-display: swap;
}`
  })

  if (preloadFontTags) {
    saveSnippet('preload-fonts', `${preloadFontTags}\n<style>${fontStyles}\n</style>\n`)
  }
}

const themeAssets = fs.readdirSync(path.resolve(__dirname, assetsDir))

const findHashedFile = (fileName) => {
  const ext = path.extname(fileName)
  const baseName = path.basename(fileName, ext)

  const matched = themeAssets.find(
    (file) => file.includes(baseName) && file.endsWith(ext)
  )

  return matched || fileName
}

const processAssetUrls = (html) => {
  return html.replace(
    /(src|href)="([^"]*?\/)?([a-zA-Z0-9_\-]+\.(?:png|jpg|jpeg|svg|webp|gif|ico|woff2?))"/g,
    '$1="{{ \'$3\' | asset_url }}"'
  ).replace(
    /url\((['"]?)(?:[^'"]*?\/)?([a-zA-Z0-9_\-]+\.(?:png|jpg|jpeg|svg|webp|gif|ico|woff2?))\1\)/g,
    (match, quote, fileName) => `url({{ '${findHashedFile(fileName)}' | asset_url }})`
  )
}

export const generatePreloadTags = (preloadFileName, lcp, lcpType) => {
  const lcpMap = Object.entries(lcp).reduce((acc, [mode, fileName]) => ({
    ...acc,
    [mode]: {
      file: lcpType === 'product' 
          ? fileName 
          : getFiles().find(f => f.startsWith(`react-${fileName}`) && (f.endsWith('.png') || f.endsWith('.webp'))),
      media: media[mode]
    }
  }), {})

  if (Object.keys(lcpMap).length !== 0) {
    const preloadTags = Object.values(lcpMap).map(({ file, media }) => (
      `<link rel="preload" as="image" href="${lcpType === 'product' ? file : `{{ '${file}' | asset_url }}`}" fetchpriority="high" media="${media}">`
    )).join('\n')
    saveSnippet(preloadFileName, preloadTags)
  }
}

